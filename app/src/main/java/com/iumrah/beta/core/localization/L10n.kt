    fun text(key: String, language: AppLanguage): String =
        dictionary[language.code]?.get(key) ?: dictionary["en"]?.get(key) ?: key

    fun format(key: String, language: AppLanguage, vararg args: Any): String {
        // Swift/Foundation uses %@ for object interpolation; java.util.Formatter uses %s.
        // Normalize only that token so numeric specifiers (%d, %.0f, …) retain source semantics.
        val format = text(key, language).replace("%@", "%s")
        return runCatching { String.format(language.locale, format, *args) }
            .getOrElse { text(key, language) }
    }

    fun city(raw: String, language: AppLanguage): String = when (raw.trim().lowercase()) {
        "makkah", "mecca" -> text("city_makkah", language)
        "madinah", "medina" -> text("city_madinah", language)
        else -> raw
    }

    fun date(raw: String, language: AppLanguage): String {
        val source = raw.trim().take(10)
        val parsed = runCatching { LocalDate.parse(source) }.getOrNull() ?: return raw
        return runCatching {
            parsed.format(DateTimeFormatter.ofLocalizedDate(FormatStyle.MEDIUM).withLocale(language.locale))
        }.getOrDefault(raw)
    }

    fun status(raw: String, language: AppLanguage): String = when (raw.uppercase()) {
        "NEW", "AVAILABILITY_CHECK" -> text("status_availability", language)
        "PAYMENT_PENDING" -> text("status_payment", language)
        "PAID", "BOOKING_CONFIRMED" -> text("status_confirmed", language)
        "DOCUMENTS_READY", "READY_TO_TRAVEL" -> text("status_ready", language)
        "IN_TRIP" -> text("status_in_trip", language)
        "COMPLETED" -> text("status_completed", language)
        "CANCELLED" -> text("status_cancelled", language)
        else -> raw.replace('_', ' ').lowercase().replaceFirstChar { it.titlecase(language.locale) }
    }
